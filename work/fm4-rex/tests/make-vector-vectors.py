"""Deterministic finite VMX arithmetic fixtures using exact rational arithmetic.

No host floating-point arithmetic is used to compute expected results. Rounding
is binary nearest-even. Dot product grouping follows Xenia Canary, with one
binary64 rounding per addition and a final binary32 conversion. NaN payloads
and real-Xenon hardware conformance are outside this oracle's scope.
"""
from fractions import Fraction as Q
from pathlib import Path
import random


def power(e):
    return Q(1 << e) if e >= 0 else Q(1, 1 << -e)


def decode(bits, fraction_bits=23, exponent_bits=8):
    mask = (1 << exponent_bits) - 1
    exponent = (bits >> fraction_bits) & mask
    assert exponent != mask
    fraction = bits & ((1 << fraction_bits) - 1)
    bias = (1 << (exponent_bits - 1)) - 1
    value = Q(fraction + ((1 << fraction_bits) if exponent else 0))
    value *= power((exponent if exponent else 1) - bias - fraction_bits)
    return -value if bits >> (fraction_bits + exponent_bits) else value


def rounded_bits(value, fraction_bits=23, exponent_bits=8):
    sign = (1 << (fraction_bits + exponent_bits)) if value < 0 else 0
    value = abs(value)
    if not value:
        return 0
    bias = (1 << (exponent_bits - 1)) - 1
    e = value.numerator.bit_length() - value.denominator.bit_length()
    if value < power(e):
        e -= 1
    e = max(e, 1 - bias)
    scaled = value / power(e - fraction_bits)
    mantissa, remainder = divmod(scaled.numerator, scaled.denominator)
    if 2 * remainder > scaled.denominator or (2 * remainder == scaled.denominator and mantissa & 1):
        mantissa += 1
    if mantissa >= 1 << (fraction_bits + 1):
        mantissa >>= 1
        e += 1
    if e > bias:
        return sign | (((1 << exponent_bits) - 1) << fraction_bits)
    if mantissa < (1 << fraction_bits):
        return sign | mantissa
    return sign | ((e + bias) << fraction_bits) | (mantissa - (1 << fraction_bits))


def flushed(bits):
    return bits if bits & 0x7f800000 else bits & 0x80000000


def fma(a, b, c, subtract=False):
    value = decode(flushed(a)) * decode(flushed(b))
    value += (-1 if subtract else 1) * decode(flushed(c))
    bits = flushed(rounded_bits(value))
    return bits ^ (0x80000000 if subtract else 0)


def add64(a, b):
    return decode(rounded_bits(a + b, 52, 11), 52, 11)


def dot(a, b, count):
    p = [decode(flushed(x)) * decode(flushed(y)) for x, y in zip(a, b)]
    value = add64(add64(p[3], p[1]), p[2] if count == 3 else add64(p[2], p[0]))
    bits = rounded_bits(value)
    if (bits & 0x7fffffff) == 0x7f800000:
        return 0x7fc00000
    return flushed(bits)


# Check the oracle against exact known encodings and halfway-even boundaries.
assert rounded_bits(Q(1)) == 0x3f800000
assert rounded_bits(Q(-2)) == 0xc0000000
assert rounded_bits(Q(1) + power(-24)) == 0x3f800000
assert rounded_bits(Q(1) + 3 * power(-24)) == 0x3f800002
assert rounded_bits(power(-149)) == 1
assert rounded_bits(power(128)) == 0x7f800000
assert fma(0x3f800001, 0x3f7ffffe, 0xbf800000) == 0xa8800000

rng = random.Random(0x4d530910)
def finite():
    return (rng.getrandbits(1) << 31) | (rng.randrange(1, 255) << 23) | rng.getrandbits(23)

fmas = [(0x3f800001, 0x3f7ffffe, 0xbf800000),
        (0x7f7fffff, 0x40000000, 0xff7fffff),
        (0x00800000, 0x3f000000, 0),
        (0x007fffff, 0x7f7fffff, 0x3f800000)]
for _ in range(256):
    fmas.append((finite(), finite(), finite()))
for _ in range(256):
    a = (127 << 23) | rng.getrandbits(23)
    b = (126 << 23) | rng.getrandbits(23)
    c = rounded_bits(decode(a) * decode(b)) ^ 0x80000000
    fmas.append((a, b, c))

dots = [([0x40800000, 0x40400000, 0x40000000, 0x3f800000], [0x3f800000] * 4),
        ([0x7f7fffff] * 4, [0x40000000] * 4),
        ([0, 0xbf800000, 0, 0x3f800001], [0, 0x3f800000, 0, 0x3f7ffffe]),
        ([0x7f7fffff, 0, 0, 0], [0x7f7fffff] * 4)]
for _ in range(256):
    dots.append(([finite() for _ in range(4)], [finite() for _ in range(4)]))

def hexes(values):
    return ', '.join(f'0x{x:08x}u' for x in values)

lines = ['// Generated by make-vector-vectors.py; exact rational oracle.', '#pragma once',
         'struct FMAVectorCase { uint32_t a, b, c, add, nsub; };',
         'inline constexpr FMAVectorCase kFMAVectors[] = {']
for a, b, c in fmas:
    lines.append('  {' + hexes([a, b, c, fma(a, b, c), fma(a, b, c, True)]) + '},')
lines += ['};', 'struct DotVectorCase { uint32_t a[4], b[4], dot3, dot4; };',
          'inline constexpr DotVectorCase kDotVectors[] = {']
for a, b in dots:
    lines.append('  {{' + hexes(a) + '}, {' + hexes(b) + '}, ' + hexes([dot(a, b, 3), dot(a, b, 4)]) + '},')
lines += ['};', '']
Path(__file__).with_name('vector-vectors.h').write_text('\n'.join(lines))
print(f'Generated {len(fmas)} FMA triples and {len(dots)} dot-product pairs.')
